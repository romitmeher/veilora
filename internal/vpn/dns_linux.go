//go:build linux

package vpn

import (
	"fmt"
	"os"
	"os/exec"
	"strings"
)

const resolvConf = "/etc/resolv.conf"
const resolvConfBackup = "/etc/resolv.conf.zen-backup"

func getSystemDNS() (string, error) {
	data, err := os.ReadFile(resolvConf)
	if err != nil {
		return "", fmt.Errorf("read resolv.conf: %w", err)
	}
	return string(data), nil
}

func setSystemDNS(resolver string) error {
	// Back up original resolv.conf.
	orig, err := os.ReadFile(resolvConf)
	if err != nil {
		return fmt.Errorf("read resolv.conf: %w", err)
	}
	if err := os.WriteFile(resolvConfBackup, orig, 0644); err != nil { // #nosec G703 -- destination is a fixed /etc path; file contents do not control the path.
		return fmt.Errorf("backup resolv.conf: %w", err)
	}

	content := fmt.Sprintf("# Generated by Zen VPN DNS protection\nnameserver %s\n", resolver)
	if err := os.WriteFile(resolvConf, []byte(content), 0644); err != nil {
		return fmt.Errorf("write resolv.conf: %w", err)
	}

	// If systemd-resolved is active, also update via resolvectl.
	if isSystemdResolved() {
		exec.Command("resolvectl", "dns", "tun0", resolver).Run()
	}
	return nil
}

func restoreSystemDNS(prev string) error {
	if prev == "" {
		// Restore from backup if we have one.
		if _, err := os.Stat(resolvConfBackup); err == nil {
			backup, err := os.ReadFile(resolvConfBackup)
			if err != nil {
				return fmt.Errorf("read backup resolv.conf: %w", err)
			}
			if err := os.WriteFile(resolvConf, backup, 0644); err != nil { // #nosec G703 -- destination is the fixed resolvConf constant.
				return fmt.Errorf("restore resolv.conf: %w", err)
			}
			os.Remove(resolvConfBackup)
			return nil
		}
		return nil
	}
	return os.WriteFile(resolvConf, []byte(prev), 0644)
}

func isSystemdResolved() bool {
	out, err := exec.Command("systemctl", "is-active", "systemd-resolved").Output()
	if err != nil {
		return false
	}
	return strings.TrimSpace(string(out)) == "active"
}
